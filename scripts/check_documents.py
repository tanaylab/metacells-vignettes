"""Check that the generated documents are usable.

The documents are generated by the CI server and published without being committed, so nothing
compares them against a previous version. These checks are what stands between a broken conversion
and a broken web site. They deliberately assert properties rather than exact content, so that a new
version of the tool chain rendering the same thing differently does not fail them.

Each failure is reported as a GitHub Actions annotation as well as on the standard output, because
annotations are visible on the workflow run page without being signed in, while the log is not.
"""

import re
import sys
from pathlib import Path
from typing import List

from pypdf import PdfReader

DOCS = Path("docs")

#: The smallest a document can be and still hold a whole vignette.
MIN_HTML_BYTES = 100 * 1024

MIN_PDF_BYTES = 100 * 1024

#: The fewest pages and characters of text a vignette can have.
MIN_PDF_PAGES = 10

MIN_PDF_CHARACTERS = 10 * 1024

#: Anything a browser would have to fetch over the network to display the document. A plain link in
#: the text is not one of these; only what the document loads to render itself is.
EXTERNAL_RESOURCE = re.compile(r'(?:src="(?:https?:)?//)|(?:<link\b[^>]*href="(?:https?:)?//)')

#: An SVG figure inlined into the document rather than embedded as an image, which is what made the
#: documents slow to load.
INLINE_SVG = re.compile(r"<svg\b")


def check_html(path: Path, problems: List[str]) -> None:
    """Check one generated HTML document."""
    size = path.stat().st_size
    if size < MIN_HTML_BYTES:
        problems.append(f"{path}: only {size} bytes, expected at least {MIN_HTML_BYTES}")

    text = path.read_text(errors="replace")

    external = sorted(set(match.group(0) for match in EXTERNAL_RESOURCE.finditer(text)))
    if external:
        problems.append(f"{path}: fetches {len(external)} resource(s) over the network: {external[:3]}")

    inline_svgs = len(INLINE_SVG.findall(text))
    if inline_svgs > 0:
        problems.append(f"{path}: has {inline_svgs} inline SVG figure(s), which should be PNG images")

    images = text.count("<img")
    if images == 0:
        problems.append(f"{path}: has no images at all")

    if 'src="data:image' not in text:
        problems.append(f"{path}: no image is embedded in it")


def check_pdf(path: Path, problems: List[str]) -> None:
    """Check one generated PDF document."""
    size = path.stat().st_size
    if size < MIN_PDF_BYTES:
        problems.append(f"{path}: only {size} bytes, expected at least {MIN_PDF_BYTES}")

    try:
        reader = PdfReader(str(path))
        n_pages = len(reader.pages)
        characters = sum(len(page.extract_text() or "") for page in reader.pages)
        images = sum(len(page.images) for page in reader.pages)
    except Exception as exception:  # pylint: disable=broad-exception-caught
        problems.append(f"{path}: cannot be read as a PDF: {exception}")
        return

    if n_pages < MIN_PDF_PAGES:
        problems.append(f"{path}: only {n_pages} pages, expected at least {MIN_PDF_PAGES}")
    if characters < MIN_PDF_CHARACTERS:
        problems.append(f"{path}: only {characters} characters of text, expected at least {MIN_PDF_CHARACTERS}")
    if images == 0:
        problems.append(f"{path}: has no figures at all")


def main() -> int:
    """Check every generated document, and report what is wrong with each."""
    notebooks = sorted(Path("notebooks").glob("*.ipynb"))
    if not notebooks:
        print("::error::there are no notebooks to generate documents from")
        return 1

    problems: List[str] = []
    for notebook in notebooks:
        for suffix, check in ((".html", check_html), (".pdf", check_pdf)):
            path = DOCS / (notebook.stem + suffix)
            if not path.exists():
                problems.append(f"{path}: was not generated")
            else:
                check(path, problems)

    for problem in problems:
        path, description = problem.split(": ", 1)
        print(f"::error file={path}::{description}")
        print(f"FAILED {problem}")

    if problems:
        print(f"\n{len(problems)} problem(s) in the generated documents")
        return 1

    for notebook in notebooks:
        for suffix in (".html", ".pdf"):
            path = DOCS / (notebook.stem + suffix)
            print(f"OK {path}: {path.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
